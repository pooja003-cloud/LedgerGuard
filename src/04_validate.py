"""
LedgerGuard: Validate the exception register against the answer key
===================================================================

The answer key (data/answer_key/answer_key.csv) lists every invoice where a
problem was planted by src/01_generate_data.py. This script compares it with what the SQL rules
flagged (v_exceptions) and reports, per scenario:

    caught           planted AND flagged          (true positives)
    missed           planted but NOT flagged      (false negatives)
    false alarms     flagged but NOT planted      (false positives)
    precision        caught / everything flagged
    recall           caught / everything planted
    $ planted vs $ flagged

Results are printed and saved to docs/validation_results.md.

Run:  python src/04_validate.py
"""

import sqlite3
from pathlib import Path

import pandas as pd

PROJECT_ROOT = Path(__file__).resolve().parents[1]
DB_PATH = PROJECT_ROOT / "data" / "ledgerguard.db"
VIEWS_SQL = PROJECT_ROOT / "sql" / "02_exceptions.sql"
KEY_PATH = PROJECT_ROOT / "data" / "answer_key" / "answer_key.csv"
OUT_PATH = PROJECT_ROOT / "docs" / "validation_results.md"

# Which rule is supposed to catch which planted scenario
SCENARIO_TO_RULE = {
    "A_Double_Discount": "PRICE_BELOW_CONTRACT",
    "B_Phantom_Short_Shipment": "CHARGEBACK_OVER_CAP",
    "C_Defective_Batch": "RETURN_SPIKE",
}


def load_flagged() -> pd.DataFrame:
    # Read-only, in-memory copy: the database file is never changed
    src = sqlite3.connect(f"file:{DB_PATH}?mode=ro", uri=True)
    conn = sqlite3.connect(":memory:")
    src.backup(conn)
    src.close()
    if not conn.execute("SELECT 1 FROM sqlite_master WHERE name='v_exceptions'").fetchone():
        conn.executescript(VIEWS_SQL.read_text())
    flagged = pd.read_sql("SELECT invoice_id, exception_type, impact_usd FROM v_exceptions", conn)
    conn.close()
    return flagged


def main():
    key = pd.read_csv(KEY_PATH).rename(columns={"Invoice_ID": "invoice_id"})
    key["rule"] = key["Scenario"].map(SCENARIO_TO_RULE)
    flagged = load_flagged()

    rows = []
    for scenario, rule in SCENARIO_TO_RULE.items():
        planted = set(key.loc[key.Scenario == scenario, "invoice_id"])
        hits = set(flagged.loc[flagged.exception_type == rule, "invoice_id"])
        caught, missed, false_alarms = planted & hits, planted - hits, hits - planted
        rows.append({
            "Scenario": scenario,
            "Rule": rule,
            "Planted": len(planted),
            "Flagged": len(hits),
            "Caught": len(caught),
            "Missed": len(missed),
            "False alarms": len(false_alarms),
            "Precision": len(caught) / len(hits) if hits else float("nan"),
            "Recall": len(caught) / len(planted) if planted else float("nan"),
            "$ planted": key.loc[key.Scenario == scenario, "Expected_Leakage_USD"].sum(),
            "$ flagged": flagged.loc[flagged.exception_type == rule, "impact_usd"].sum(),
        })

    # Rules with no planted scenario (e.g. markdown cap) should flag nothing
    other = flagged[~flagged.exception_type.isin(SCENARIO_TO_RULE.values())]

    res = pd.DataFrame(rows)
    total = {"Scenario": "TOTAL", "Rule": "",
             **{c: res[c].sum() for c in ["Planted", "Flagged", "Caught", "Missed",
                                           "False alarms", "$ planted", "$ flagged"]}}
    total["Flagged"] += len(other)
    total["False alarms"] += len(other)
    total["Precision"] = total["Caught"] / total["Flagged"]
    total["Recall"] = total["Caught"] / total["Planted"]
    res = pd.concat([res, pd.DataFrame([total])], ignore_index=True)

    fmt = res.copy()
    for c in ["Precision", "Recall"]:
        fmt[c] = fmt[c].map(lambda v: f"{v:.0%}")
    for c in ["$ planted", "$ flagged"]:
        fmt[c] = fmt[c].map(lambda v: f"${v:,.0f}")

    print(fmt.to_string(index=False))
    print(f"\nFlags from rules with no planted scenario: {len(other)}")

    OUT_PATH.parent.mkdir(exist_ok=True)
    OUT_PATH.write_text(
        "# Validation against the answer key\n\n"
        "Generated by `src/04_validate.py`. Compares invoices flagged by `v_exceptions` "
        "with the problems planted by `src/01_generate_data.py`.\n\n"
        + fmt.to_markdown(index=False)
        + f"\n\nFlags from rules with no planted scenario (markdown cap): {len(other)}\n"
    )
    print(f"Saved {OUT_PATH.relative_to(PROJECT_ROOT)}")


if __name__ == "__main__":
    main()
